// Generates extension production configuration.
//   DEVLAUNCH_APP_URL  - deployed DevLaunch AI origin (defaults to localhost in dev)
// Writes:
//   public/extension/config.js   - runtime API origin for popup/background
//   public/extension/manifest.json - host_permissions derived from the origin
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const extDir = path.resolve(__dirname, '../public/extension');

const raw = process.env.DEVLAUNCH_APP_URL || 'http://localhost:3000';
const appUrl = raw.replace(/\/+$/, '');
let origin;
try {
  origin = new URL(appUrl).origin;
} catch {
  console.error(`Invalid DEVLAUNCH_APP_URL: ${raw}`);
  process.exit(1);
}

const hostPermission = `${origin}/*`;

writeFileSync(
  path.join(extDir, 'config.js'),
  `// Generated by scripts/build-extension-config.mjs - do not edit.\nwindow.DEVLAUNCH_CONFIG = ${JSON.stringify({ apiUrl: origin }, null, 2)};\n`
);

const template = JSON.parse(
  readFileSync(path.join(extDir, 'manifest.template.json'), 'utf8')
);
template.host_permissions = [hostPermission];
writeFileSync(path.join(extDir, 'manifest.json'), `${JSON.stringify(template, null, 2)}\n`);

console.log(`Extension configured for ${origin} (host_permissions: ${hostPermission})`);